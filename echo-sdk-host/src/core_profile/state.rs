//! Shared state of the negotiated core profile.
//!
//! The state owns the durable stores (generation, state root, run index),
//! the handle registry, the cached per-run journals and the live ACK-gated
//! deliveries. It deliberately does **not** own Session maps, run
//! terminals, retries or event sequences — those stay with the shared
//! [`echo_agent::acp::AcpConnectionServices`] and the framework driver.

